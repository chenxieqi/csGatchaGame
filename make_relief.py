"""Gives the silver parts of one gacha AK skin a raised (embossed), pearly look.

    python make_relief.py l_AK_Gothic_Horror [strength]

Only bright, low-saturation pixels (silver ornaments and lines) are treated as silver;
everything else keeps its original color, metalness and roughness and stays flat.
From maps/skin_texture/{name}.png it writes into maps/gacha_ak/maps/:
  {id}_relief_color.png   color with bevel light/shadow baked onto the silver parts
  {id}_relief_normal.png  normal map (OpenGL / Y+), flat everywhere except the silver bevels
  {id}_relief_metal.png   metalness: silver parts fully metal
  {id}_relief_rough.png   roughness: silver parts polished
  {id}_relief_fxmask.png  effect mask = silver parts (pearly sheen goes only there)
and rewrites maps/gacha_ak/{id}.vmat to use them, with a pearl-like iridescent
sheen on the silver and no glitter. The original texture is not touched.
Running gen_gacha_ak.ps1 for this skin again rewrites the vmat: run this again after.
Close CS2 Workshop Tools first if you can: textures rewritten while the tools are
compiling them can come out as colored noise.
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ADDON = Path(__file__).resolve().parent
name = sys.argv[1].removesuffix(".png")
strength = float(sys.argv[2]) if len(sys.argv) > 2 else 1.0
skin_id = name.lower()
src = ADDON / "maps" / "skin_texture" / f"{name}.png"
maps_dir = ADDON / "maps" / "gacha_ak" / "maps"
vmat = ADDON / "maps" / "gacha_ak" / f"{skin_id}.vmat"


def to_img(a):
    return Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8))


# Metalness / roughness / mask / normal maps must be a power of two (the compiler
# can't build their mips otherwise); the color texture may keep its own size.
AUX = 1024


def save_aux(a, path):
    to_img(a).resize((AUX, AUX), Image.LANCZOS).save(path, optimize=True)


def blur(a, r):
    return np.asarray(to_img(a).filter(ImageFilter.GaussianBlur(r)), dtype=np.float32) / 255.0


rgb = np.asarray(Image.open(src).convert("RGB"), dtype=np.float32) / 255.0
mx, mn = rgb.max(axis=2), rgb.min(axis=2)
sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-6), 0)
lum = rgb @ np.array([0.299, 0.587, 0.114], dtype=np.float32)

# Silver = bright and grey. Soft edges, then cleaned of single-pixel speckles.
silver = np.clip((lum - 0.28) / 0.14, 0, 1) * np.clip((0.42 - sat) / 0.12, 0, 1)
silver = np.asarray(to_img(silver).filter(ImageFilter.MedianFilter(3)).filter(ImageFilter.MaxFilter(3)), dtype=np.float32) / 255.0
silver = np.clip(blur(silver, 0.8) * 1.2, 0, 1)

# Height: a smooth rounded bevel built only from the silver mask (no surface grain)
height = blur(silver, 1.5)
k = 6.0 * strength
dx = (np.roll(height, -1, axis=1) - np.roll(height, 1, axis=1)) * 0.5 * k
dy = (np.roll(height, -1, axis=0) - np.roll(height, 1, axis=0)) * 0.5 * k
n = np.dstack([-dx, dy, np.ones_like(height)])  # Y+: up in the image is +Y
n /= np.linalg.norm(n, axis=2, keepdims=True)
save_aux(n * 0.5 + 0.5, maps_dir / f"{skin_id}_relief_normal.png")

# Baked bevel: light from the upper left on the silver, shadow cast to the lower right
light = np.array([-0.55, 0.55, 0.63], dtype=np.float32)
light /= np.linalg.norm(light)
shade = n @ light - light[2]                                   # 0 where flat
cast = np.roll(np.roll(blur(silver, 2.5), 3, axis=0), 3, axis=1) # silver shifted down-right
shadow = np.clip(cast - silver, 0, 1)                          # falls only beside the silver
factor = 1 + 1.6 * strength * shade * np.clip(height * 2, 0, 1) - 0.55 * strength * shadow
color = rgb * factor[..., None]
# A faint cool pearl tint on the silver itself
pearl_tint = np.array([1.0, 1.02, 1.06], dtype=np.float32)
color = color * (1 - silver[..., None] * 0.5) + color * pearl_tint * (silver[..., None] * 0.5)
to_img(color).save(maps_dir / f"{skin_id}_relief_color.png", optimize=True)

# Silver: fully metal and polished. Elsewhere: the generator's maps, untouched.
def load_gray(path, fallback):
    p = maps_dir / path
    if not p.exists():
        return np.full(lum.shape, fallback, dtype=np.float32)
    g = Image.open(p).convert("L").resize((lum.shape[1], lum.shape[0]), Image.BILINEAR)
    return np.asarray(g, dtype=np.float32) / 255.0

metal = load_gray(f"{skin_id}_metal.png", 0.0)
rough = load_gray(f"{skin_id}_rough.png", 0.5)
save_aux(metal * (1 - silver) + 1.0 * silver, maps_dir / f"{skin_id}_relief_metal.png")
save_aux(rough * (1 - silver) + 0.12 * silver, maps_dir / f"{skin_id}_relief_rough.png")
save_aux(silver, maps_dir / f"{skin_id}_relief_fxmask.png")

# Material
p = f"maps/gacha_ak/maps/{skin_id}_relief"
vmat.write_text(f"""// Generated by make_relief.py from {name}.png (silver relief + pearl sheen)
"Layer0"
{{
\t"shader"\t\t"csgo_weapon.vfx"
\t"TextureColor1"\t\t"{p}_color.png"
\t"TextureNormal"\t\t"{p}_normal.png"
\t"TextureMetalness1"\t\t"{p}_metal.png"
\t"TextureRoughness1"\t\t"{p}_rough.png"
\t"g_vMetalnessRemapRange"\t\t"[0.000 1.000]"
\t"F_ENABLE_SFX_MASK"\t\t"1"
\t"TextureSfxMask1"\t\t"{p}_fxmask.png"
\t"F_IRIDESCENCE"\t\t"1"
\t"g_flIridescentStrength"\t\t"{0.6 * strength:.3f}"
\t"g_flIridescentScale"\t\t"0.800"
\t"g_flIridescentHueShift"\t\t"0.150"
\t"g_flModelTintAmount"\t\t"1.000000"
\t"g_vColorTint"\t\t"[1.000000 1.000000 1.000000 0.000000]"
\t"g_vTexCoordCenter"\t\t"[0.500 0.500]"
\t"g_vTexCoordOffset"\t\t"[0.000 0.000]"
\t"g_vTexCoordScale"\t\t"[1.000 1.000]"
\t"g_flTexCoordRotation"\t\t"0.000000"
\t"g_flUvScale1"\t\t"1.000000"
}}
""", encoding="utf-8")
print(f"silver covers {silver.mean() * 100:.1f}% of the texture; wrote {skin_id}_relief_* and {vmat.name}")
