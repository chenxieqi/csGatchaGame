/** @param {string} args */
function parseAmount(args) {
    const n = parseInt(args.trim().split(/\s+/).pop() ?? "", 10);
    return Number.isFinite(n) ? n : undefined;
}

Instance.RegisterCheatCommand("gacha_coins", (args) => {
    const n = parseAmount(args);
    if (n !== undefined) {
        coins = Math.max(0, n);
        updateCoinsText();
    }
    Instance.Msg(`[gacha] coins: ${coins}`);
});

Instance.RegisterCheatCommand("gacha_addcoins", (args) => {
    coins = Math.max(0, coins + (parseAmount(args) ?? 0));
    updateCoinsText();
    Instance.Msg(`[gacha] coins: ${coins}`);
});

Instance.RegisterCheatCommand("gacha_clear", () => clearDroppedWeapons());

Instance.RegisterCheatCommand("gacha_reset_skins", () => {
    inventory = [];
    updateCoinsText();
    refreshShowcase();
    Instance.Msg("[gacha] collected skins cleared");
});
